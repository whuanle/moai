using MoAI.Database.Schema;
using Xunit;

namespace MoAI.Database.Tests;

public class SchemaScriptParserTests
{
    private const string Script = """
        CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

        CREATE SEQUENCE external_id_seq START WITH 1 INCREMENT BY 1 NO CYCLE;

        CREATE TABLE access_app (
            id uuid NOT NULL DEFAULT (uuid_generate_v4()),
            name character varying(50) NOT NULL,
            level integer NOT NULL DEFAULT 0,
            callback_urls text NOT NULL,
            CONSTRAINT idx_access_app_primary PRIMARY KEY (id)
        );
        COMMENT ON TABLE access_app IS '应用接入';
        COMMENT ON COLUMN access_app.id IS 'id';

        CREATE TABLE "user" (
            id bigint GENERATED BY DEFAULT AS IDENTITY,
            user_name character varying(50) NOT NULL,
            is_deleted bigint NOT NULL DEFAULT ('0'::bigint),
            CONSTRAINT user_pkey PRIMARY KEY (id)
        );

        INSERT INTO "user" (id, user_name) VALUES (1, 'admin(测试)');
        INSERT INTO skill (id, instructions) VALUES (1, '# 说明
        exec(open(''a.py'').read())  -- 文案里的括号 ( 不应影响切分');
        INSERT INTO skill (id, instructions) VALUES (2, '第二行 ()');

        CREATE INDEX idx_access_app_level ON access_app (level);
        CREATE UNIQUE INDEX idx_access_app_key_uindex ON access_app (name, is_deleted);
        CREATE INDEX idx_user_name_index ON "user" (user_name);
        """;

    [Fact]
    public void SplitStatements_SeparatesStatementsWithMultilineLiterals()
    {
        var statements = SchemaScriptParser.SplitStatements(Script);

        Assert.Equal(2, statements.Count(x => x.StartsWith("CREATE TABLE ", StringComparison.Ordinal)));
        Assert.Equal(2, statements.Count(x => x.StartsWith("CREATE INDEX ", StringComparison.Ordinal)));
        Assert.Equal(1, statements.Count(x => x.StartsWith("CREATE UNIQUE INDEX ", StringComparison.Ordinal)));
        Assert.Equal(2, statements.Count(x => x.StartsWith("INSERT INTO skill", StringComparison.Ordinal)));
        Assert.Contains(statements, x => x.StartsWith("CREATE INDEX idx_user_name_index ON \"user\"", StringComparison.Ordinal));
    }

    [Fact]
    public void Parse_ReadsTablesColumnsAndIndexes()
    {
        var tables = SchemaScriptParser.Parse(Script);

        Assert.Equal(2, tables.Count);

        var accessApp = Assert.Single(tables, x => x.RawName == "access_app");
        Assert.Equal("access_app", accessApp.Name);
        Assert.Equal(["id", "name", "level", "callback_urls"], accessApp.Columns.Select(x => x.RawName));
        Assert.Equal(2, accessApp.IndexStatements.Count);

        var user = Assert.Single(tables, x => x.RawName == "user");
        Assert.Equal("\"user\"", user.Name);
        Assert.Equal(["id", "user_name", "is_deleted"], user.Columns.Select(x => x.RawName));
        Assert.Single(user.IndexStatements);
    }

    [Fact]
    public void Parse_ReadsColumnMetadata()
    {
        var tables = SchemaScriptParser.Parse(Script);
        var accessApp = tables.Single(x => x.RawName == "access_app");

        var name = accessApp.Columns.Single(x => x.RawName == "name");
        Assert.Equal("character varying(50)", name.TypeName);
        Assert.Equal(50, name.MaxLength);
        Assert.True(name.IsRequired);
        Assert.False(name.HasDefault);

        var level = accessApp.Columns.Single(x => x.RawName == "level");
        Assert.True(level.HasDefault);
        Assert.Equal("integer", level.TypeName);

        var id = tables.Single(x => x.RawName == "user").Columns.Single(x => x.RawName == "id");
        Assert.True(id.IsIdentity);
    }
}
