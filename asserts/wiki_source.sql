-- 外部源：知识库下的一类外部数据入口（飞书文档 / 爬虫），持有同步方式与工作流预设
create table if not exists wiki_source (
  id uuid not null default uuid_generate_v4(),
  wiki_id integer not null,
  team_id integer not null,
  source_type integer not null default 0,
  name varchar(50) not null,
  description varchar(255) not null default ''::character varying,
  config text not null default ''::text,
  workflow_config text not null default ''::text,
  is_enable boolean not null default true,
  cron varchar(64) not null default ''::character varying,
  is_event_subscription boolean not null default false,
  last_sync_time timestamptz,
  last_sync_status integer not null default 0,
  last_sync_message varchar(1000) not null default ''::character varying,
  create_user_id bigint not null default 0,
  create_time timestamptz not null default timezone('utc', now()),
  update_user_id bigint not null default 0,
  update_time timestamptz not null default timezone('utc', now()),
  is_deleted bigint not null default 0,
  constraint wiki_source_pkey primary key (id)
);
