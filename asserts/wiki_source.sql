-- 外部源文档：外部源条目与知识库文档的映射，记录内容哈希用于增量比对
create table if not exists wiki_source_document (
  id bigint generated by default as identity,
  source_id uuid not null,
  wiki_id integer not null,
  team_id integer not null,
  document_id integer not null,
  external_key varchar(128) not null,
  external_doc_token varchar(128) not null default ''::character varying,
  external_title varchar(255) not null default ''::character varying,
  external_path varchar(1000) not null default ''::character varying,
  content_hash varchar(64) not null default ''::character varying,
  revision varchar(64) not null default ''::character varying,
  status integer not null default 0,
  last_sync_time timestamptz,
  last_error varchar(1000) not null default ''::character varying,
  create_user_id bigint not null default 0,
  create_time timestamptz not null default timezone('utc', now()),
  update_user_id bigint not null default 0,
  update_time timestamptz not null default timezone('utc', now()),
  is_deleted bigint not null default 0,
  constraint wiki_source_document_pkey primary key (id)
);
