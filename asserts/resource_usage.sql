comment on column "resource_usage_total".name is '资源类型名，如 plugin-usage / app-usage / skill-usage';
comment on column "resource_usage_total".resource_id is '资源 id 文本，各资源主键形态不一（Guid/int/key），统一以字符串存储';
comment on column "resource_usage_total".total is '累计总量';

-- 同一 (资源类型, 资源id) 只允许一行，落库走 upsert 累加
create unique index if not exists idx_resource_usage_total_name_resource_uindex
    on "resource_usage_total" (name, resource_id);
