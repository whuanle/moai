comment on column "resource_usage_daily".name is '资源类型名，如 plugin-usage / app-usage / skill-usage';
comment on column "resource_usage_daily".resource_id is '资源 id 文本，各资源主键形态不一（Guid/int/key），统一以字符串存储';
comment on column "resource_usage_daily".count is '当日累计数量';

-- usage_hour（统计粒度按小时桶）为后加列：存量库幂等补齐，旧三列唯一索引替换为四列
alter table "resource_usage_daily" add column if not exists usage_hour integer not null default -1;
drop index if exists idx_resource_usage_daily_date_name_resource_uindex;

-- 同一 (日期, 小时, 资源类型, 资源id) 只允许一行，落库走 upsert 累加
create unique index if not exists idx_resource_usage_daily_date_hour_name_resource_uindex
    on "resource_usage_daily" (usage_date, usage_hour, name, resource_id);
create index if not exists idx_resource_usage_daily_name_date_index
    on "resource_usage_daily" (name, usage_date);

-- 资源使用统计（总量）：统计模块定期批量落库，按 资源类型+资源id 累计总量，不按日隔离
create table if not exists "resource_usage_total" (
    id bigint generated by default as identity,
    name varchar(100) not null,
    resource_id varchar(128) not null,
    total bigint not null default 0,
    create_time timestamptz not null default timezone('utc'::text, now()),
    update_time timestamptz not null default timezone('utc'::text, now()),
    constraint idx_resource_usage_total_primary primary key (id)
);
