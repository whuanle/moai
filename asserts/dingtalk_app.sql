-- 钉钉应用：一个钉钉开放平台企业内部应用（AppKey/AppSecret）对应一条 Stream 长连接，
-- 机器人消息由钉钉模块统一接收后按绑定转发
create table if not exists dingtalk_app (
  id uuid not null default uuid_generate_v4(),
  name varchar(50) not null,
  description varchar(255) not null default ''::character varying,
  team_id integer not null,
  app_key varchar(64) not null,
  app_secret varchar(128) not null,
  chatbot_user_id varchar(128) not null default ''::character varying,
  is_disable boolean not null default false,
  create_user_id bigint not null default 0,
  create_time timestamptz not null default timezone('utc',now()),
  update_user_id bigint not null default 0,
  update_time timestamptz not null default timezone('utc',now()),
  is_deleted bigint not null default 0,
  constraint dingtalk_app_pkey primary key (id)
);
