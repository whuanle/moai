-- 变量管理模块增量 DDL：team_variable（团队变量）
-- 本仓库无 EF Migration（启动 EnsureCreated 只对空库生效），
-- 已有数据库新增表需手动执行本文件；同时保持与
-- src/database 下 TeamVariableEntity 及其 Configuration 一致。
-- 软删除为 boolean（同 team 模块约定）。

CREATE TABLE IF NOT EXISTS public.team_variable (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id         bigint       NOT NULL,
    group_name      varchar(50)  NOT NULL DEFAULT '',
    key             varchar(100) NOT NULL,
    value           text         NOT NULL DEFAULT '',
    is_secret       boolean      NOT NULL DEFAULT false,
    description     varchar(255) NOT NULL DEFAULT '',
    is_deleted      boolean      NOT NULL DEFAULT false,
    create_user_id  bigint       NOT NULL DEFAULT 0,
    create_time     timestamptz  NOT NULL DEFAULT timezone('utc'::text, now()),
    update_user_id  bigint       NOT NULL DEFAULT 0,
    update_time     timestamptz  NOT NULL DEFAULT timezone('utc'::text, now())
);

COMMENT ON TABLE public.team_variable IS '团队变量，插件配置以 ${key} 引用';
COMMENT ON COLUMN public.team_variable.id IS '变量ID，自增主键';
COMMENT ON COLUMN public.team_variable.team_id IS '所属团队ID，逻辑关联team.id（仓库约定不建物理外键）';
COMMENT ON COLUMN public.team_variable.group_name IS '分组名，仅组织用途不参与寻址，空串=未分组';
COMMENT ON COLUMN public.team_variable.key IS '变量名，团队内唯一（字母开头，字母/数字/下划线）';
COMMENT ON COLUMN public.team_variable.value IS '变量值；普通变量明文，私密变量 AES 密文';
COMMENT ON COLUMN public.team_variable.is_secret IS '是否私密变量：true 值仅管理员可见';
COMMENT ON COLUMN public.team_variable.description IS '变量描述，最长255字符，空串=未填写';
COMMENT ON COLUMN public.team_variable.is_deleted IS '软删除：false=未删除，true=已删除（审计钩子经接口适配自动写入）';
COMMENT ON COLUMN public.team_variable.create_user_id IS '创建人用户ID，审计钩子插入时自动填充';
COMMENT ON COLUMN public.team_variable.create_time IS '创建时间，审计钩子自动填充，默认timezone(utc,now())';
COMMENT ON COLUMN public.team_variable.update_user_id IS '最后修改人用户ID，审计钩子更新/删除时自动填充';
COMMENT ON COLUMN public.team_variable.update_time IS '更新时间，审计钩子插入/更新/删除时自动刷新';

CREATE INDEX IF NOT EXISTS idx_team_variable_team_id ON public.team_variable (team_id);
-- partial 唯一索引：同团队内未删除变量名唯一，删除后同名可重建
CREATE UNIQUE INDEX IF NOT EXISTS idx_team_variable_team_key_live_uindex ON public.team_variable (team_id, key) WHERE is_deleted = false;

ALTER TABLE public.team_variable
    OWNER to postgres;
