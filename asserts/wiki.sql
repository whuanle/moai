-- 知识库模块增量 DDL：wiki（知识库，挂团队）
-- 本仓库无 EF Migration（启动 EnsureCreated 只对空库生效），
-- 已有数据库新增表需手动执行本文件；同时保持与
-- src/database 下 WikiEntity 及其 Configuration 一致。
-- 软删除为 boolean（同 team 模块约定），唯一约束用 partial index。

CREATE TABLE IF NOT EXISTS public.wiki (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id         bigint       NOT NULL,
    name            varchar(50)  NOT NULL,
    description     varchar(255) NOT NULL DEFAULT '',
    is_deleted      boolean      NOT NULL DEFAULT false,
    create_user_id  bigint       NOT NULL DEFAULT 0,
    create_time     timestamptz  NOT NULL DEFAULT timezone('utc'::text, now()),
    update_user_id  bigint       NOT NULL DEFAULT 0,
    update_time     timestamptz  NOT NULL DEFAULT timezone('utc'::text, now())
);

COMMENT ON TABLE public.wiki IS '知识库，挂在团队下的资源';
COMMENT ON COLUMN public.wiki.id IS '知识库ID，自增主键';
COMMENT ON COLUMN public.wiki.team_id IS '所属团队ID，逻辑关联team.id（仓库约定不建物理外键）';
COMMENT ON COLUMN public.wiki.name IS '知识库名称，最长50字符';
COMMENT ON COLUMN public.wiki.description IS '知识库简介，最长255字符，空串=未填写';
COMMENT ON COLUMN public.wiki.is_deleted IS '软删除：false=未删除，true=已删除（审计钩子经接口适配自动写入）';
COMMENT ON COLUMN public.wiki.create_user_id IS '创建人用户ID，审计钩子插入时自动填充';
COMMENT ON COLUMN public.wiki.create_time IS '创建时间，审计钩子自动填充，默认timezone(utc,now())';
COMMENT ON COLUMN public.wiki.update_user_id IS '最后修改人用户ID，审计钩子更新/删除时自动填充';
COMMENT ON COLUMN public.wiki.update_time IS '更新时间，审计钩子插入/更新/删除时自动刷新';

CREATE INDEX IF NOT EXISTS idx_wiki_team_id ON public.wiki (team_id);
-- partial 唯一索引：仅约束未删除行，同一团队内未删除同名不允许，删除后同名可重建
CREATE UNIQUE INDEX IF NOT EXISTS idx_wiki_team_name_live_uindex ON public.wiki (team_id, name) WHERE is_deleted = false;

ALTER TABLE public.wiki
    OWNER to postgres;


-- 知识库文档（二期：内容层）
CREATE TABLE IF NOT EXISTS public.wiki_document (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wiki_id         bigint       NOT NULL,
    title           varchar(100) NOT NULL,
    content         text         NOT NULL DEFAULT '',
    is_deleted      boolean      NOT NULL DEFAULT false,
    create_user_id  bigint       NOT NULL DEFAULT 0,
    create_time     timestamptz  NOT NULL DEFAULT timezone('utc'::text, now()),
    update_user_id  bigint       NOT NULL DEFAULT 0,
    update_time     timestamptz  NOT NULL DEFAULT timezone('utc'::text, now())
);

COMMENT ON TABLE public.wiki_document IS '知识库文档，挂在知识库下的内容页';
COMMENT ON COLUMN public.wiki_document.id IS '文档ID，自增主键';
COMMENT ON COLUMN public.wiki_document.wiki_id IS '所属知识库ID，逻辑关联wiki.id（仓库约定不建物理外键）';
COMMENT ON COLUMN public.wiki_document.title IS '文档标题，最长100字符';
COMMENT ON COLUMN public.wiki_document.content IS '文档内容（Markdown，text 不限长）';
COMMENT ON COLUMN public.wiki_document.is_deleted IS '软删除：false=未删除，true=已删除（审计钩子经接口适配自动写入）';
COMMENT ON COLUMN public.wiki_document.create_user_id IS '创建人用户ID，审计钩子插入时自动填充';
COMMENT ON COLUMN public.wiki_document.create_time IS '创建时间，审计钩子自动填充，默认timezone(utc,now())';
COMMENT ON COLUMN public.wiki_document.update_user_id IS '最后修改人用户ID，审计钩子更新/删除时自动填充';
COMMENT ON COLUMN public.wiki_document.update_time IS '更新时间，审计钩子插入/更新/删除时自动刷新';

CREATE INDEX IF NOT EXISTS idx_wiki_document_wiki_id ON public.wiki_document (wiki_id);

ALTER TABLE public.wiki_document
    OWNER to postgres;
