-- 通知中心（notification_channel / notification_log）：统一通知渠道配置与发送记录
-- 与 src/database/MoAI.Database.Postgres/DatabasPostgresModule.cs 的幂等 DDL 等价（存量库免手工执行）
CREATE TABLE IF NOT EXISTS notification_channel (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    name varchar(100) NOT NULL,
    type int NOT NULL DEFAULT 1,
    config varchar(4000) NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    description varchar(500) NOT NULL DEFAULT ''::character varying,
    create_user_id bigint NOT NULL DEFAULT 0,
    create_time timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
    update_user_id bigint NOT NULL DEFAULT 0,
    update_time timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
    is_deleted bigint NOT NULL DEFAULT 0,
    CONSTRAINT idx_notification_channel_primary PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_notification_channel_name_uindex ON notification_channel (name) WHERE is_deleted = 0;

CREATE TABLE IF NOT EXISTS notification_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    channel_id bigint NOT NULL DEFAULT 0,
    channel_name varchar(100) NOT NULL DEFAULT ''::character varying,
    channel_type int NOT NULL DEFAULT 1,
    level int NOT NULL DEFAULT 0,
    title varchar(256) NOT NULL,
    content varchar(4000) NOT NULL,
    status int NOT NULL DEFAULT 0,
    error varchar(1000) NOT NULL DEFAULT ''::character varying,
    duration_ms bigint NOT NULL DEFAULT 0,
    target_user_ids varchar(1000) NOT NULL DEFAULT ''::character varying,
    recipients varchar(1000) NOT NULL DEFAULT ''::character varying,
    create_user_id bigint NOT NULL DEFAULT 0,
    create_time timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
    update_user_id bigint NOT NULL DEFAULT 0,
    update_time timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
    is_deleted bigint NOT NULL DEFAULT 0,
    CONSTRAINT idx_notification_log_primary PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_notification_log_time ON notification_log (create_time DESC) WHERE is_deleted = 0;
CREATE INDEX IF NOT EXISTS idx_notification_log_channel ON notification_log (channel_id, create_time DESC) WHERE is_deleted = 0;
ALTER TABLE notification_log ADD COLUMN IF NOT EXISTS target_user_ids character varying(1000) NOT NULL DEFAULT ''::character varying;
ALTER TABLE notification_log ADD COLUMN IF NOT EXISTS recipients character varying(1000) NOT NULL DEFAULT ''::character varying;

CREATE TABLE IF NOT EXISTS notification_template (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    code varchar(64) NOT NULL DEFAULT ''::character varying,
    name varchar(100) NOT NULL,
    title varchar(256) NOT NULL DEFAULT ''::character varying,
    content varchar(10000) NOT NULL,
    content_type int NOT NULL DEFAULT 0,
    variables varchar(4000) NOT NULL DEFAULT ''::character varying,
    aliyun_template_code varchar(128) NOT NULL DEFAULT ''::character varying,
    tencent_template_id varchar(128) NOT NULL DEFAULT ''::character varying,
    description varchar(500) NOT NULL DEFAULT ''::character varying,
    create_user_id bigint NOT NULL DEFAULT 0,
    create_time timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
    update_user_id bigint NOT NULL DEFAULT 0,
    update_time timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
    is_deleted bigint NOT NULL DEFAULT 0,
    CONSTRAINT idx_notification_template_primary PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_notification_template_name_uindex ON notification_template (name) WHERE is_deleted = 0;
ALTER TABLE notification_template ADD COLUMN IF NOT EXISTS code varchar(64) NOT NULL DEFAULT ''::character varying;
CREATE UNIQUE INDEX IF NOT EXISTS idx_notification_template_code_uindex ON notification_template (code) WHERE is_deleted = 0 AND code <> '';

COMMENT ON TABLE notification_channel IS '通知中心渠道：统一承接飞书/钉钉/企业微信/Telegram/通用 webhook/SMTP/站内推送等通知出口配置';
COMMENT ON COLUMN notification_channel.name IS '渠道名称（唯一）';
COMMENT ON COLUMN notification_channel.type IS '渠道类型';
COMMENT ON COLUMN notification_channel.config IS '渠道配置 JSON（按渠道类型结构化，含 webhook 地址/密钥/收件人等）';
COMMENT ON COLUMN notification_channel.enabled IS '是否启用';
COMMENT ON COLUMN notification_channel.description IS '渠道描述';

COMMENT ON TABLE notification_log IS '通知发送记录：通知中心每次对单渠道投递一条，记录最终状态与耗时';
COMMENT ON COLUMN notification_log.channel_id IS '渠道 id';
COMMENT ON COLUMN notification_log.channel_name IS '渠道名称快照（渠道删除后仍可读）';
COMMENT ON COLUMN notification_log.channel_type IS '渠道类型';
COMMENT ON COLUMN notification_log.level IS '通知级别';
COMMENT ON COLUMN notification_log.title IS '通知标题';
COMMENT ON COLUMN notification_log.content IS '通知正文（超长截断存档）';
COMMENT ON COLUMN notification_log.status IS '发送状态';
COMMENT ON COLUMN notification_log.error IS '失败原因';
COMMENT ON COLUMN notification_log.duration_ms IS '发送耗时（毫秒）';
COMMENT ON COLUMN notification_log.target_user_ids IS '关联用户 id 快照（逗号分隔，定向个人推送时记录收件人；空为广播/全员）';
COMMENT ON COLUMN notification_log.recipients IS '实际收件人快照（逗号分隔；SMTP 渠道记邮箱、短信渠道记手机号；固定地址渠道留空）';

COMMENT ON TABLE notification_template IS '通知中心模板：文本 + 变量定义，发送时插值生成通知内容；可携带阿里云/腾讯云短信平台已审核模板映射';
COMMENT ON COLUMN notification_template.code IS '内置模板标识 code（如 register_email_code，非空表示平台内置模板：不可删除、可编辑，业务按 code 回退解析）';
COMMENT ON COLUMN notification_template.name IS '模板名称（唯一）';
COMMENT ON COLUMN notification_template.title IS '通知主题模板（邮件主题用，短信无主题）';
COMMENT ON COLUMN notification_template.content IS '通知正文模板（纯文本或 HTML，含 {{变量}} 双花括号占位符）';
COMMENT ON COLUMN notification_template.content_type IS '内容类型';
COMMENT ON COLUMN notification_template.variables IS '变量定义 JSON（[{"name","description","example"}]，发送时按 name 提供变量值）';
COMMENT ON COLUMN notification_template.aliyun_template_code IS '阿里云短信模板 Code（平台审核通过后回填，空表示不用于阿里云短信）';
COMMENT ON COLUMN notification_template.tencent_template_id IS '腾讯云短信模板 Id（平台审核通过后回填，空表示不用于腾讯云短信）';
COMMENT ON COLUMN notification_template.description IS '模板描述';
